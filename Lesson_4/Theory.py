import pandas as pd
import numpy as np

data = {
    'Продукт': ['A', 'B', 'C', 'A', 'B', 'C', 'A', 'B', 'C', 'A'],
    'Цена': [10.5, 20.0, 5.5, 11.0, 20.0, 6.0, 10.5, 22.0, 5.5, 100.0],
    'Количество': [100, 50, 200, 90, 60, 150, 110, 40, 210, 80]
}
df = pd.DataFrame(data)

#Главные методы в этом уроке - "Описательная статистика с Pandas"

# Получение 8 основных метрик (Count, Mean, Std, Min, 25%, 50%, 75%, Max)
print(df[['Цена', 'Количество']].describe())

"""
count (количество непустых значений)
mean (среднее)
std (стандартное отклонение)
min (минимальное значение)
25% (первый квартиль, Q)
50% (медиана, Q)
75% (третий квартиль)
max (максимальное значение)

             Цена  Количество
count   10.000000   10.000000
mean    21.100000  109.000000
std     28.421236   59.712273
min      5.500000   40.000000
25%      7.125000   65.000000
50%     10.750000   95.000000
75%     20.000000  140.000000
max    100.000000  210.000000
"""

#Центр распределения (Mean, Median, Mode)

# Среднее (Mean)
mean_price = df['Цена'].mean()
print(f"Средняя цена: {mean_price:.2f}")

"""Средняя цена: 21.10"""


# Медиана (Median)
median_price = df['Цена'].median()
print(f"Медианная цена: {median_price:.2f}")

"""Медианная цена: 10.75"""


# Мода (Mode)
mode_price = df['Цена'].mode()
print(f"Модальная(ые) цена(ы): {mode_price.tolist()}")

"""Модальная(ые) цена(ы): [5.5, 10.5, 20.0]"""

#Разброс и Квартили (Std, Min/Max, Quantile)

# Стандартное отклонение (Std)
std_qty = df['Количество'].std()
print(f"Стандартное отклонение 'Количество': {std_qty:.2f}")
# Высокое значение std (65.36) указывает на большой разброс в количестве.

"""Стандартное отклонение 'Количество': 59.71"""

# Минимальное и Максимальное
min_price = df['Цена'].min()
max_price = df['Цена'].max()
print(f"Диапазон цен: {min_price} - {max_price}")

"""Диапазон цен: 5.5 - 100.0"""

# Первый квартиль (25-й перцентиль)
q1_price = df['Цена'].quantile(0.25)
print(f"Первый квартиль (Q1): {q1_price:.2f}")

"""Первый квартиль (Q1): 7.12"""

#4. Форма распределения (Skew, Kurt)

# Асимметрия (Skewness)
skew_price = df['Цена'].skew()
print(f"Асимметрия 'Цены': {skew_price:.2f}")
# Положительное значение (2.95) указывает на длинный "хвост" справа (выброс 100.0).

"""Асимметрия 'Цены': 2.88"""

# Эксцесс (Kurtosis)
kurt_price = df['Цена'].kurt()
print(f"Эксцесс 'Цены': {kurt_price:.2f}")
# Положительный эксцесс (8.54) означает более "тяжелые" хвосты, чем у нормального распределения (или наличие выбросов).

"""Эксцесс 'Цены': 8.69"""

#5. Анализ категориальных данных (.value_counts())

# Подсчет уникальных значений для 'Продукт'
product_counts = df['Продукт'].value_counts()
print("\nКоличество продаж по продуктам:")
print(product_counts)

"""
Количество продаж по продуктам:
Продукт
A    4
B    3
C    3
Name: count, dtype: int64
"""

#6. Групповой анализ (.groupby())

# Среднее 'Количество' для каждого 'Продукта'
mean_qty_by_product = df.groupby('Продукт')['Количество'].mean()
print("\nСреднее количество по продукту:")
print(mean_qty_by_product)

"""
Среднее количество по продукту:
Продукт
A     95.000000
B     50.000000
C    186.666667
Name: Количество, dtype: float64
"""
